#!/usr/bin/env bash
# fm-spawn.sh hook: when FM_HOOK_BEADS_ID is set, stamp the linked bead as
# dispatched and register a watcher check that wakes firstmate for teardown
# once the bead closes. Sourced by fm-spawn.sh inside a subshell after a
# successful spawn; a bare `exit 0` below only ends that subshell, never
# fm-spawn.sh itself. Fail-open throughout: every failure here warns on
# stderr and continues rather than disturbing the spawn that already succeeded.
set -u

[ -n "${FM_HOOK_BEADS_ID:-}" ] || exit 0

BEADS_ID=$FM_HOOK_BEADS_ID
TASK_ID=${FM_HOOK_ID:-}
STATE=${FM_HOOK_STATE:-}
ROOT=${FM_HOOK_ROOT:-}

if [ -z "$TASK_ID" ] || [ -z "$STATE" ] || [ -z "$ROOT" ]; then
  echo "warning: beads spawn hook missing required FM_HOOK_* context, skipping" >&2
  exit 0
fi

"$ROOT/bin/fm-bead-stamp.sh" "$BEADS_ID" "$TASK_ID" || true

if ! command -v task >/dev/null 2>&1; then
  echo "warning: task CLI not found on PATH, skipping bead-close watcher check for $BEADS_ID" >&2
  exit 0
fi

CHECK="$STATE/$TASK_ID.check.sh"
old_umask=$(umask)
umask 077
cat > "$CHECK" <<CHECKEOF
#!/usr/bin/env bash
# Registered check for task $TASK_ID (bin/fm-check-register.sh): polls whether
# bead $BEADS_ID has closed, and prints exactly one line to wake firstmate
# when it has. Prints nothing otherwise. Generated by bin/fm-spawn-hooks.d/beads.sh.
set -u
json=\$(task show $BEADS_ID --json 2>/dev/null) || exit 0
case "\$json" in
  *'"status"'*'"closed"'*) printf 'bead closed: %s\n' "$BEADS_ID" ;;
esac
CHECKEOF
umask "$old_umask"
chmod 0700 "$CHECK"

if ! FM_STATE_OVERRIDE="$STATE" "$ROOT/bin/fm-check-register.sh" "$TASK_ID"; then
  echo "warning: could not register bead-close watcher check for $TASK_ID (bead $BEADS_ID)" >&2
fi

exit 0
